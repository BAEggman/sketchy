import json, re
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
DATA=ROOT/'src/panels'
READ=json.loads((DATA/'readings.json').read_text())
PANELS=[]

def t(value):
    def add(m):
        han,kor=m.groups()
        if han in READ and READ[han]!=kor:
            raise ValueError((han,READ[han],kor))
        READ[han]=kor
        return han
    return re.sub(r'\[([^\[\]|]+)\|([가-힣]+)\]',add,value)

def panel(pid,title,audit,kind,labels,refs,links=(),note=''):
    p=dict(id=pid,title=title,tag='음양오행·보완',track='D',image=f'images/{pid}.svg',rows=[],quiz=[],
           extension='yinyang-v2.4',audit_ids=audit,diagram=dict(kind=kind,labels=labels),
           sources=[{'title':a,'url':b} for a,b in links],source_notes=refs,study_note=note)
    PANELS.append(p)
    return p

def row(p,prop,fact,why,q,trap=False,extra=()):
    fact=t(fact); why=t(why)
    p['rows'].append(dict(prop=prop,fact=fact,why=why,trap=trap))
    p['quiz'].append(dict(q=q,a=fact,src=p['source_notes'][0]))
    for question,answer in extra:p['quiz'].append(dict(q=question,a=t(answer),src=p['source_notes'][0]))

