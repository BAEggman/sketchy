def write():
    # Every Han phrase in facts/answers must have an explicitly reviewed reading.
    cjk=re.compile(r'[\u3400-\u9fff\uf900-\ufaff]+')
    missing=set()
    for p in PANELS:
        for text in [r['fact'] for r in p['rows']]+[q['a'] for q in p['quiz']]:
            missing.update(w for w in cjk.findall(text) if w not in READ)
    if missing:raise ValueError(('unreviewed readings',sorted(missing)))
    (DATA/'yinyang-v2.4.json').write_text(json.dumps(PANELS,ensure_ascii=False,indent=2)+'\n')
    (DATA/'readings.json').write_text(json.dumps(READ,ensure_ascii=False,indent=2)+'\n')
    print(f'{len(PANELS)} panels, {sum(len(p["rows"]) for p in PANELS)} facts, {sum(len(p["quiz"]) for p in PANELS)} questions')

if __name__=='__main__':write()
