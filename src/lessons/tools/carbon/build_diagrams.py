FONT_CANDIDATES = [
    '/System/Library/Fonts/AppleSDGothicNeo.ttc',
    '/System/Library/Fonts/Supplemental/AppleGothic.ttf',
    '/System/Library/Fonts/STHeiti Medium.ttc',
]


def get_font(size: int, bold: bool = False):
    for fp in FONT_CANDIDATES:
        if Path(fp).exists():
            try:
                # AppleSDGothicNeo.ttc index 6 is Bold, 0 is Regular
                idx = 6 if (bold and fp.endswith('AppleSDGothicNeo.ttc')) else 0
                return ImageFont.truetype(fp, size, index=idx)
            except Exception:
                return ImageFont.truetype(fp, size)
    return ImageFont.load_default()


def base_canvas(title: str, subtitle: str):
    W, H = 2048, 2048
    im = Image.new('RGB', (W, H), (253, 251, 245))
    dr = ImageDraw.Draw(im)
    # 바깥 둥근 테두리
    dr.rounded_rectangle([38, 38, W - 38, H - 38], radius=24, outline=(59, 47, 47), width=6, fill=(253, 251, 245))
    f_title = get_font(64, bold=True)
    f_sub = get_font(34, bold=False)
    dr.text((W // 2, 118), title, font=f_title, fill=(35, 30, 30), anchor='mm')
    dr.text((W // 2, 192), subtitle, font=f_sub, fill=(70, 65, 60), anchor='mm')
    dr.line([140, 240, W - 140, 240], fill=(160, 150, 140), width=2)
    return im, dr


def draw_table_diagram(out_id: str, title: str, subtitle: str, headers: list, col_xs: list, rows: list, footers: list):
    im, dr = base_canvas(title, subtitle)
    W = 2048
    f_hdr = get_font(28, bold=True)
    f_cell_b = get_font(24, bold=True)
    f_cell = get_font(22, bold=False)
    f_foot_b = get_font(28, bold=True)
    f_foot = get_font(24, bold=False)

    # 헤더
    y = 285
    dr.rounded_rectangle([110, y - 28, W - 110, y + 34], radius=10, fill=(242, 238, 228), outline=(90, 80, 70), width=2)
    for h_txt, cx in zip(headers, col_xs):
        dr.text((cx, y + 2), h_txt, font=f_hdr, fill=(40, 35, 35), anchor='mm')

    # 행
    y = 355
    row_h = min(98, (1520 - y) // max(1, len(rows)))
    palette = [
        (246, 242, 233),
        (238, 245, 251),
        (241, 248, 238),
        (252, 240, 238),
        (250, 246, 232),
    ]
    for r_idx, row in enumerate(rows):
        bg = palette[r_idx % len(palette)]
        dr.rounded_rectangle([110, y, W - 110, y + row_h - 8], radius=8, fill=bg)
        cy = y + (row_h - 8) // 2
        for c_idx, (val, cx) in enumerate(zip(row, col_xs)):
            f_use = f_cell_b if c_idx in (0, 1) else f_cell
            col = (180, 35, 35) if ('★' in val or '일렉기타' in val or '삼지창' in val or '구미호' in val or '팔레트' in val or '버스' in val or '사과' in val or '오징어' in val or '너트' in val or '칠면조' in val or '공룡' in val) and c_idx == len(row) - 1 else (35, 30, 30)
            dr.text((cx, cy), val, font=f_use, fill=col, anchor='mm')
        y += row_h

    # 하단 요약 상자
    fy = max(y + 24, 1580)
    for f_title_txt, f_desc_txt, box_bg in footers:
        dr.rounded_rectangle([110, fy, W - 110, fy + 118], radius=16, fill=box_bg, outline=(60, 50, 50), width=3)
        dr.text((W // 2, fy + 38), f_title_txt, font=f_foot_b, fill=(165, 35, 30), anchor='mm')
        dr.text((W // 2, fy + 84), f_desc_txt, font=f_foot, fill=(45, 40, 40), anchor='mm')
        fy += 136

    CARBON_DIAG.mkdir(parents=True, exist_ok=True)
    im.save(IMG_DIR / f'{out_id}.webp', 'WEBP', quality=90)
    im.save(CARBON_DIAG / f'{out_id}.png')
    print(f'Built diagram {out_id}.webp (2048x2048)')


