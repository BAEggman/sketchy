def build_hist_lessons():
    M = json.loads((LESSONS / 'lesson_map.json').read_text(encoding='utf-8'))
    map_by_id = {x['id']: x for x in M['lessons']}
    all_questions = {}

    # 1. 분리된 14개 과(hist-01a/b .. 08a/b) 생성
    for lid, st_specs in SPLIT_SPECS.items():
        m = map_by_id[lid]
        W, H = 2752, 1536
        boxes = grid_boxes(len(st_specs), W, H)
        stations = [{
            'n': 0,
            'kind': 'frame',
            'obj': m['place'],
            'fact': f"{m['title']} ({len(st_specs)} 정거장)"[:60],
            'hook': m['place'].split(' — ')[0],
            'say': f"{m['title']} 과다. 장소는 {m['place']}. 왼쪽에서 오른쪽으로 시대를 따라 인물 묶음의 발밑 왕조 터, 몸의 이름·자호, 손의 서명·기여, 금메달(최초)과 숫자 물건을 차례로 읽는다.",
            'box': None,
            'src': [],
        }]
        q_list = []
        for idx, (obj, fact, hook, say, src, attrs_raw) in enumerate(st_specs, start=1):
            bx = boxes[idx - 1]
            attrs = []
            for a in attrs_raw:
                vessel = ['문항'] if a['link'] in ('문항', '이야기') else ['그림', '문항']
                if a['link'] == '이야기':
                    vessel = ['이야기', '문항']
                attrs.append({
                    'slot': a['slot'],
                    'obj': a['obj'],
                    'fact': a['fact'],
                    'link': a['link'],
                    'box': bx,
                    'vessel': vessel,
                })
                q_list.append({
                    'station': idx,
                    'slot': a['slot'],
                    'q': f"[{m['title']} #{idx}] 그림의 「{a['obj']}」이(가) 가리키는 [{a['slot']}]은?",
                    'a': a['fact'],
                    'src': src,
                })
            stations.append({
                'n': idx,
                'obj': obj,
                'fact': fact[:60],
                'hook': hook,
                'say': say,
                'box': bx,
                'src': src,
                'attrs': attrs,
            })
        # review 정거장
        rev_n = len(st_specs) + 1
        rev_cards = []
        for s in m['stations']:
            for c in s.get('cards', []):
                if c not in rev_cards:
                    rev_cards.append(c)
        stations.append({
            'n': rev_n,
            'kind': 'review',
            'obj': '전체 구역 왼쪽 → 오른쪽 되짚기',
            'fact': f"되짚기 — {m['title']}"[:60],
            'hook': '발밑=왕조 · 몸=이름/字號 · 손=서명/기여 · 메달=최초 · 수 부호',
            'say': '왼쪽부터 다시 한 바퀴 되짚는다. ' + ' / '.join(s['fact'] for s in stations[1:rev_n]),
            'box': boxes[:min(4, len(boxes))],
            'src': rev_cards[:6],
        })
        assert len(stations) == m['n_stations'], f"{lid}: {len(stations)} != {m['n_stations']}"

        for st in stations:
            st['tts'] = make_tts.convert_text_to_tts(st['say'])[0]

        L = {
            'id': lid,
            'title': m['title'],
            'place': m['place'],
            'image': f'images/lessons/{lid}.webp',
            'w': W,
            'h': H,
            'design': f'src/lessons/design/{lid}/',
            'stations': stations,
        }
        (LESSONS / 'l' / f'{lid}.json').write_text(json.dumps(L, ensure_ascii=False, indent=1) + '\n', encoding='utf-8')
        (CARBON / 'questions').mkdir(parents=True, exist_ok=True)
