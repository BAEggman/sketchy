def tts(s):
    for t in sorted(READ, key=len, reverse=True):
        s = s.replace(t, READ[t])
    left = re.findall(r'[一-鿿]+', s)
    if left:
        raise SystemExit('독음이 없는 한자: ' + ' '.join(sorted(set(left))))
    return re.sub(r'\s+', ' ', s).strip()


def main(paths):
    for (k, (lid, title, place, frame_obj, frame_fact, frame_say, boxes)), src in zip(LESSONS.items(), paths):
        im = Image.open(src).convert('RGB')
        assert im.size == (2752, 1536), (src, im.size)
        out = os.path.join(ROOT, 'images/lessons', lid + '.webp')
        im.save(out, 'WEBP', quality=90, method=6)
        T = FINAL['targets'][k]
        st = [{'n': 0, 'kind': 'frame', 'obj': frame_obj, 'fact': frame_fact, 'hook': '사건 한 컷 — 손이 책에 닿아 기여 동사를 함',
               'say': frame_say, 'box': None, 'src': ['runs/20261120-p2-hist/final.json'], 'tts': tts(frame_say)}]
        for s in T['stations']:
            b = boxes[s['n']]
            assert b[0] >= 0 and b[1] >= 0 and b[0] + b[2] <= 2752 and b[1] + b[3] <= 1536, (lid, s['n'], b)
            st.append({'n': s['n'], 'obj': s['obj'], 'fact': s['fact'], 'hook': s['hook'], 'say': s['say'], 'box': b,
                       'src': ['runs/20261120-p2-hist/final.json'], 'tts': tts(s['say'])})
        L = {'id': lid, 'title': title, 'place': place, 'image': 'images/lessons/%s.webp' % lid, 'w': 2752, 'h': 1536,
             'stations': st, 'attrs': {'pilot': 'P2', 'run': '20261120-p2-hist', 'target': k,
                                       'raw': '~/Downloads/sketchy_opus/gemini_raw/' + RAW[k],
                                       'questions': T['questions']}}
        json.dump(L, open(os.path.join(ROOT, 'src/lessons/l', lid + '.json'), 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
        print('written', lid, len(st), 'stations ·', os.path.getsize(out) // 1024, 'KB')


if __name__ == '__main__':
    main(sys.argv[1:5])
